/** Check if user input matches expected romaji or acceptable variants */
export function checkRomajiMatch(input: string, item: KanaItem): boolean {
  const normalized = input.trim().toLowerCase();
  if (!normalized) return false;

  if (normalized === item.romaji.toLowerCase()) {
    return true;
  }

  if (item.alternatives && item.alternatives.some((alt) => alt.toLowerCase() === normalized)) {
    return true;
  }

  return false;
}
